//! The colour data of every shadcn theme, as shadcn-vue's `apps/v4/registry/themes.ts` (pin `d1bf1b3`) writes it:
//! each base colour's whole palette in light and dark, and what each accent overrides. Generated once from that file
//! into Rust values and checked in; nothing reads upstream at build or run time. Each colour is `[l, c, h, alpha]`, as
//! CSS `oklch(l c h / alpha)`.

use super::palette::{Palette, Palettes};

/// `[l, c, h, alpha]`.
pub(super) type Raw = [f32; 4];

/// The tokens an accent writes over its base colour, in one scheme.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(super) struct Overrides {
    pub(super) primary: Raw,
    pub(super) primary_foreground: Raw,
    pub(super) secondary: Raw,
    pub(super) secondary_foreground: Raw,
    pub(super) chart: [Raw; 5],
    pub(super) sidebar_primary: Raw,
    pub(super) sidebar_primary_foreground: Raw,
    /// Only rose's dark scheme writes `sidebar` (`themes.ts:946`), with zinc's dark sidebar; kept as upstream has it.
    pub(super) sidebar: Option<Raw>,
}

/// An accent's overrides in light and dark.
#[derive(Clone, Copy, Debug, PartialEq)]
pub(super) struct AccentData {
    pub(super) light: Overrides,
    pub(super) dark: Overrides,
}

