//! Icons by role, drawn from the icon library a theme selects (ADR-0022, research §7.3).
//!
//! A component asks for an [`IconRole`] (`ChevronDown`, `Close`, `Check`…); the theme's [`IconSet`] supplies its
//! glyph as a [`gui::Icon`]. `gui` reads the glyph's SVG into paths, rasterizes it once per size on the GPU into its
//! mask atlas and tints it with the colour the icon is drawn in (`currentColor`), as for any icon.
//!
//! The five libraries are those of shadcn-vue's icon loader (`registry/icons/create-icon-loader.ts`), each a cargo
//! feature of this crate: `lucide` (the default), `tabler`, `hugeicons`, `phosphor` and `remixicon`. Each carries only
//! the glyphs the roles need, vendored under `assets/icons/<library>/` with its licence (`THIRD_PARTY.md`).
//!
//! The role → glyph table is the props of the `IconPlaceholder`s in shadcn-vue's base (`registry/bases/reka/ui`,
//! pin `d1bf1b3`):
//!
//! | Role | Where upstream | lucide | tabler | hugeicons | phosphor | remixicon |
//! | --- | --- | --- | --- | --- | --- | --- |
//! | `Check` | checkbox, menu and select items, command, copy done | `Check` | `Check` | `Tick02` | `Check` | `CheckLine` |
//! | `Close` | dialog, sheet, sonner, tags input | `X` | `X` | `Cancel01` | `X` | `CloseLine` |
//! | `ChevronDown` | accordion, navigation menu, select scroll down | `ChevronDown` | `ChevronDown` | `ArrowDown01` | `CaretDown` | `ArrowDownSLine` |
//! | `ChevronUp` | accordion, select scroll up | `ChevronUp` | `ChevronUp` | `ArrowUp01` | `CaretUp` | `ArrowUpSLine` |
//! | `ChevronLeft` | calendar, carousel, pagination previous | `ChevronLeft` | `ChevronLeft` | `ArrowLeft01` | `CaretLeft` | `ArrowLeftSLine` |
//! | `ChevronRight` | breadcrumb, calendar, carousel, sub-menus, pagination next, trace | `ChevronRight` | `ChevronRight` | `ArrowRight01` | `CaretRight` | `ArrowRightSLine` |
//! | `ChevronsLeft` | pagination first | `ChevronsLeft` | `ChevronsLeft` | `ArrowLeftDouble` | `CaretDoubleLeft` | `ArrowLeftDoubleLine` |
//! | `ChevronsRight` | pagination last | `ChevronsRight` | `ChevronsRight` | `ArrowRightDouble` | `CaretDoubleRight` | `ArrowRightDoubleLine` |
//! | `Selector` | select trigger, native select | `ChevronDown` | `Selector` | `UnfoldMore` | `CaretDown` | `ArrowDownSLine` |
//! | `Success` | sonner | `CircleCheck` | `CircleCheck` | `CheckmarkCircle01` | `CheckCircle` | `CheckboxCircleLine` |
//! | `Info` | sonner | `Info` | `InfoCircle` | `InformationCircle` | `Info` | `InformationLine` |
//! | `Warning` | sonner | `TriangleAlert` | `AlertTriangle` | `Alert02` | `Warning` | `AlertLine` |
//! | `Error` | sonner | `OctagonX` | `OctagonOff` | `CancelCircle` | `XCircle` | `CloseCircleLine` |
//! | `Loading` | spinner, sonner | `Loader2` | `Loader2` | `Loading03` | `SpinnerGap` | `Loader4Line` |
//! | `Circle` | radio group indicator | `Circle` | `Circle` | `Circle` | `Circle` | `CircleLine` |
//! | `Copy` | code block | `Copy` | `Copy` | `Copy01` | `Copy` | `FileCopyLine` |
//! | `Minus` | number field, pin input and OTP separators | `Minus` | `Minus` | `MinusSign` | `Minus` | `SubtractLine` |
//! | `Plus` | number field | `Plus` | `Plus` | `Add01` | `Plus` | `AddLine` |
//! | `Search` | command, combobox | `Search` | `Search` | `Search01` | `MagnifyingGlass` | `SearchLine` |
//! | `More` | breadcrumb and pagination ellipsis | `MoreHorizontal` | `Dots` | `MoreHorizontalCircle01` | `DotsThree` | `MoreLine` |
//! | `Sidebar` | sidebar trigger | `PanelLeft` | `LayoutSidebar` | `SidebarLeft` | `Sidebar` | `SideBarLine` |
//! | `ArrowDown` | message scroller | `ArrowDown` | lucide's | lucide's | lucide's | lucide's |
//!
//! Where ours differs from upstream:
//! - Upstream's loader draws a glyph only if its library's module (`registry/icons/__<library>__.ts`, generated by
//!   `scripts/build-icons.ts`) re-exports it; for any other name `createIconLoader` renders nothing. At the pin, ten
//!   of the names the `IconPlaceholder`s ask for are missing from those modules, so upstream draws no icon there.
//!   Ours draws the glyph upstream names, from the library itself, which is what the placeholder means:
//!   - tabler: `IconOctagonOff` (`Error`: sonner) and `IconLoader2` (`Loading`: spinner, sonner);
//!   - hugeicons: `CancelCircleIcon` (`Error`: sonner) and `Minus01Icon` (number field, pin input). `Minus01Icon`
//!     is not in `@hugeicons/core-free-icons` at all; `Minus` gives them `MinusSign`, the glyph upstream's OTP
//!     separator uses;
//!   - phosphor: `SpinnerGapIcon` (`Loading`: spinner, sonner) and `CircleIcon` (`Circle`: radio group);
//!   - remixicon: `RiArrowLeftDoubleLine` and `RiArrowRightDoubleLine` (`ChevronsLeft`, `ChevronsRight`:
//!     pagination first and last), `RiAlertLine` (`Warning`: sonner) and `RiCircleLine` (`Circle`: radio group).
//!
//!   The verdict runs under lucide, where every name is exported; `verdict/better.tsv` records these, as comments
//!   until the verdict runs per library (its entries are per demo, and an entry would excuse a lucide diff).
//! - Upstream's command asks for `SearchIcon`, an alias of `Search01Icon`: one role.
//! - The message scroller imports lucide's `ArrowDownIcon` directly, whatever the library, and so does `ArrowDown`.

use gui::{Icon, SvgIcon};

#[cfg(not(any(
    feature = "lucide",
    feature = "tabler",
    feature = "hugeicons",
    feature = "phosphor",
    feature = "remixicon"
)))]
compile_error!(
    "shadcn needs an icon library: enable one of the features lucide, tabler, hugeicons, phosphor, remixicon"
);

/// The library [`IconSet::DEFAULT`] names: the first of [`IconSet::ALL`].
#[cfg(feature = "lucide")]
const FIRST: IconSet = IconSet::Lucide;
#[cfg(all(not(feature = "lucide"), feature = "tabler"))]
const FIRST: IconSet = IconSet::Tabler;
#[cfg(all(not(any(feature = "lucide", feature = "tabler")), feature = "hugeicons"))]
const FIRST: IconSet = IconSet::Hugeicons;
#[cfg(all(
    not(any(feature = "lucide", feature = "tabler", feature = "hugeicons")),
    feature = "phosphor"
))]
const FIRST: IconSet = IconSet::Phosphor;
#[cfg(all(
    not(any(feature = "lucide", feature = "tabler", feature = "hugeicons", feature = "phosphor")),
    feature = "remixicon"
))]
const FIRST: IconSet = IconSet::Remixicon;

/// What an icon is for. Each [`IconSet`] has a glyph for every role.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum IconRole {
    /// A checked box or item, a done copy.
    Check,
    /// Closes a dialog, sheet or toast, removes a tag.
    Close,
    /// Opens below: an accordion, a navigation menu; scrolls a select down.
    ChevronDown,
    /// An open accordion; scrolls a select up.
    ChevronUp,
    /// Previous: a calendar month, a carousel slide, a page.
    ChevronLeft,
    /// Next, and the breadcrumb separator; opens a sub-menu.
    ChevronRight,
    /// The first page.
    ChevronsLeft,
    /// The last page.
    ChevronsRight,
    /// Opens a list of options: a select's trigger.
    Selector,
    /// A toast's success.
    Success,
    /// A toast's information.
    Info,
    /// A toast's warning.
    Warning,
    /// A toast's error.
    Error,
    /// Work in progress: the spinner, a loading toast.
    Loading,
    /// A radio item's indicator.
    Circle,
    /// Copies (a code block).
    Copy,
    /// Decrements; separates the groups of a one-time code.
    Minus,
    /// Increments.
    Plus,
    /// A search field.
    Search,
    /// More items than shown: the breadcrumb's and pagination's ellipsis.
    More,
    /// Toggles the sidebar.
    Sidebar,
    /// Scrolls a message list to its latest message.
    ArrowDown,
}

impl IconRole {
    /// Every role.
    pub const ALL: &'static [IconRole] = &[
        IconRole::Check,
        IconRole::Close,
        IconRole::ChevronDown,
        IconRole::ChevronUp,
        IconRole::ChevronLeft,
        IconRole::ChevronRight,
        IconRole::ChevronsLeft,
        IconRole::ChevronsRight,
        IconRole::Selector,
        IconRole::Success,
        IconRole::Info,
        IconRole::Warning,
        IconRole::Error,
        IconRole::Loading,
        IconRole::Circle,
        IconRole::Copy,
        IconRole::Minus,
        IconRole::Plus,
        IconRole::Search,
        IconRole::More,
        IconRole::Sidebar,
        IconRole::ArrowDown,
    ];

    /// Whether the glyph points along the inline direction, so that it is mirrored under right-to-left text
    /// (upstream's `cn-rtl-flip`). Upstream mirrors the single chevrons and the sidebar trigger; the double chevrons
    /// of pagination's first and last point the same way and are mirrored too. A component whose icon turns with its
    /// state (the trace trigger's chevron) decides for itself.
    #[must_use]
    pub const fn directional(self) -> bool {
        matches!(
            self,
            IconRole::ChevronLeft
                | IconRole::ChevronRight
                | IconRole::ChevronsLeft
                | IconRole::ChevronsRight
                | IconRole::Sidebar
        )
    }
}

/// An icon library: where every [`IconRole`]'s glyph comes from. Each is a cargo feature of this crate; `Theme.icons`
/// holds the one in use.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum IconSet {
    /// Lucide (ISC), shadcn's default.
    #[cfg(feature = "lucide")]
    Lucide,
    /// Tabler Icons, outline (MIT).
    #[cfg(feature = "tabler")]
    Tabler,
    /// Hugeicons, the free stroke set (MIT).
    #[cfg(feature = "hugeicons")]
    Hugeicons,
    /// Phosphor, regular weight (MIT).
    #[cfg(feature = "phosphor")]
    Phosphor,
    /// Remix Icon, line (Apache-2.0, release 4.8.0, the last before its own licence).
    #[cfg(feature = "remixicon")]
    Remixicon,
}

impl IconSet {
    /// Every library this build carries.
    pub const ALL: &'static [IconSet] = &[
        #[cfg(feature = "lucide")]
        IconSet::Lucide,
        #[cfg(feature = "tabler")]
        IconSet::Tabler,
        #[cfg(feature = "hugeicons")]
        IconSet::Hugeicons,
        #[cfg(feature = "phosphor")]
        IconSet::Phosphor,
        #[cfg(feature = "remixicon")]
        IconSet::Remixicon,
    ];

    /// Lucide when this build carries it, as upstream's default; otherwise the first library it carries. A `const`, so
    /// a `const` theme can name it.
    pub const DEFAULT: IconSet = FIRST;

    /// Upstream's name for it (`iconLibrary` in shadcn's config), which is also its cargo feature.
    #[must_use]
    pub const fn name(self) -> &'static str {
        match self {
            #[cfg(feature = "lucide")]
            IconSet::Lucide => "lucide",
            #[cfg(feature = "tabler")]
            IconSet::Tabler => "tabler",
            #[cfg(feature = "hugeicons")]
            IconSet::Hugeicons => "hugeicons",
            #[cfg(feature = "phosphor")]
            IconSet::Phosphor => "phosphor",
            #[cfg(feature = "remixicon")]
            IconSet::Remixicon => "remixicon",
        }
    }

    /// The library named `name` (as [`IconSet::name`] gives it), if this build carries it.
    #[must_use]
    pub fn from_name(name: &str) -> Option<IconSet> {
        IconSet::ALL.iter().copied().find(|s| s.name() == name)
    }

    /// The glyph this library draws for `role`.
    #[must_use]
    pub fn icon(self, role: IconRole) -> Icon {
        Icon::Svg(self.glyph(role))
    }

    fn glyph(self, role: IconRole) -> &'static SvgIcon {
        match self {
            #[cfg(feature = "lucide")]
            IconSet::Lucide => lucide::glyph(role),
            #[cfg(feature = "tabler")]
            IconSet::Tabler => tabler::glyph(role),
            #[cfg(feature = "hugeicons")]
            IconSet::Hugeicons => hugeicons::glyph(role),
            #[cfg(feature = "phosphor")]
            IconSet::Phosphor => phosphor::glyph(role),
            #[cfg(feature = "remixicon")]
            IconSet::Remixicon => remixicon::glyph(role),
        }
    }
}

impl Default for IconSet {
    fn default() -> Self {
        IconSet::DEFAULT
    }
}

/// The message scroller's arrow: lucide's in every library, as upstream imports it.
static ARROW_DOWN: SvgIcon = SvgIcon::new(
    "lucide/arrow-down",
    include_str!("../../assets/icons/lucide/arrow-down.svg"),
);

/// A library's table: its glyphs, each a `static` read from `assets/icons/<dir>/<file>.svg`, then the glyph of every
/// role. The match is exhaustive, so a library without a glyph for some role does not build.
macro_rules! library {
    ($dir:literal; glyphs { $($glyph:ident => $file:literal,)* } roles { $($role:ident => $to:expr,)* }) => {
        $(
            static $glyph: gui::SvgIcon = gui::SvgIcon::new(
                concat!($dir, "/", $file),
                include_str!(concat!("../../assets/icons/", $dir, "/", $file, ".svg")),
            );
        )*

        pub(super) fn glyph(role: super::IconRole) -> &'static gui::SvgIcon {
            match role {
                $(super::IconRole::$role => &$to,)*
            }
        }
    };
}

